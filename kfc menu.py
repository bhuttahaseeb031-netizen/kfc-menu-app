"""### Machine Learning Model
We will train a **Random Forest Classifier** to predict the **Category** of a KFC menu item based on its **Price_USD** and **Calories**. Then, we will measure and display the model's prediction accuracy.
"""

from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report
import pandas as pd

# Prepare features (X) and target (y)
X = df[['Price_USD', 'Calories']]
y = df['Category']

# Split the dataset into training and testing sets (using a stratified split due to small size)
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.3, random_state=42, stratify=y
)

# Initialize and train the Random Forest Classifier
model = RandomForestClassifier(n_estimators=100, random_state=42)
model.fit(X_train, y_train)

# Predict on the test set
y_pred = model.predict(X_test)

# Calculate accuracy
accuracy = accuracy_score(y_test, y_pred)

print(f"Model Accuracy: {accuracy * 100:.2f}%")
print("\nClassification Report:")
print(classification_report(y_test, y_pred, zero_division=0))

"""### Optimized Machine Learning Pipeline
To improve model efficiency, reliability, and accuracy, we implement a standardized pipeline that:
1. Scales numeric features (`Price_USD` and `Calories`) using standard scaling so they share the same scale.
2. Uses cross-validated Grid Search (`GridSearchCV`) to find the most efficient hyperparameters for the Random Forest Classifier.
"""

from sklearn.model_selection import GridSearchCV
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline

# Create a pipeline combining feature scaling and classifier
pipeline = Pipeline([
    ('scaler', StandardScaler()),
    ('classifier', RandomForestClassifier(random_state=42))
])

# Define parameter grid to tune and find the most efficient parameters
param_grid = {
    'classifier__n_estimators': [10, 50, 100],
    'classifier__max_depth': [None, 3, 5],
    'classifier__min_samples_split': [2, 3]
}

# Stratified CV to handle the small sample size efficiently
grid_search = GridSearchCV(pipeline, param_grid, cv=2, scoring='accuracy', n_jobs=-1)
grid_search.fit(X_train, y_train)

# Predict and evaluate using the optimized model
best_model = grid_search.best_estimator_
y_pred_opt = best_model.predict(X_test)
opt_accuracy = accuracy_score(y_test, y_pred_opt)

print(f"Optimized Model Best Parameters: {grid_search.best_params_}")
print(f"Optimized Model Accuracy: {opt_accuracy * 100:.2f}%")
print("\nOptimized Classification Report:")
print(classification_report(y_test, y_pred_opt, zero_division=0))

